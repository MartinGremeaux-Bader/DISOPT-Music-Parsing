from data_setup import Chord, Rules, Terminal_rules, Weight, Terminal_elem, Start, P_Matrix

# NOTE : the algorthm would work just fine if you were to put another grammar in it,
# but for the type check I had to force chords into parameters.
# Just deleting the type check would make it work.

def best_sequence(t_elem : list[Chord] = Terminal_elem, rules : list[tuple[Chord, tuple[Chord, Chord]]] = Rules, end : list[tuple[Chord, Chord]] = Terminal_rules, start = Start, p_matrix = P_Matrix, Weight : function = Weight, ) -> tuple[list[Chord], float] | None :               
    '''
    \n The application of the algorithm described in the typst file.
    \n Note that we iterate on rules to have much less iterations (probably).
    \n \n The first four parameters are what we use of the grammar, the 5th is the initial weight marix and the 6th the weight function applied to the rules
    '''
    def w(rule, w_left = 0, w_right = 0): # weight of trees, so that it is in yellow in the code
        '''rule weight function'''
        return Weight(rule, w_left, w_right)
    def num(element) -> int :
        return t_elem.index(element)
    
    n = p_matrix.shape[0] # length of chord string wanted

    p_matrix *= n*(n+1)/2 # because there will be n*(n+1)/2 rules applied, we do this so that the matrix has the same weight as the rules in global,
    #and so the weight of the matrix is entirely determined by the INITIAL_WEIGHT variable in datas_setup

    P : dict[tuple[int, int], dict[Chord, tuple[float, list[Chord]]]] = dict([((i, j), dict()) for i in range(n) for j in range(i, n)])
    #each P[(i, j)] is a dict which associate a non-terminal element to a weight and a produced list of terminal elements (with this weight)
    # it will contan the string generated by the heaviest possible subtree generated by this non-terminal element
    # each dict starts empty

    # first step of cyk
    for i in range(n) :
        for T_rule in end :
            N = T_rule[0]
            a = T_rule[1]
            weight = p_matrix[i][num(a)]
            if weight != 0 :
                if not N in P[(i, i)].keys() or weight > P[(i, i)][N][0]:
                    P[(i, i)][N] = (weight, [a])


    # induction on j-i, starts at 1
    for diff in range(1, n) :
        for i in range(n-diff) :
            j = i + diff
            for k in range(i, j) :
                for rule in rules :
                    N, A, B = rule[0], rule[1][0], rule[1][1]

                    if not (A in P[(i, k)].keys() and B in P[(k+1, j)].keys()) :
                        continue

                    alpha = P[(i, k)][A]
                    beta = P[(k+1, j)][B]
                    w_A, s_A, w_B, s_B = alpha[0], alpha[1], beta[0], beta[1]
                    weight = w(rule, w_A, w_B)

                    if not N in P[(i, j)].keys() or weight > P[(i, j)][N][0] :
                        P[(i, j)][N] = (weight, s_A + s_B)
                    

    if start in P[(0, n-1)].keys() :
        return P[(0, n-1)][start][::-1]
    else :
        return None
